"""Название, которое сервис предлагает человеку, — из самого документа."""
import io

from docx import Document

from app import doc_text


def _docx(paragraphs: list[str]) -> bytes:
    doc = Document()
    for text in paragraphs:
        doc.add_paragraph(text)
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def test_заголовок_разбитый_на_абзацы_склеивается():
    data = _docx(["Приложение № 2",
                  "О строительстве общеобразовательной организации на 550 мест",
                  "по адресу г. Ульяновск, бульвар Архитекторов",
                  "(2026 год)",
                  "Далее идёт текст справки."])
    # склеенный заголовок сразу сокращается по смыслу: «организация» — это школа
    assert doc_text.title_from("справка.docx", data) == (
        "О строительстве школы на 550 мест "
        "по адресу г. Ульяновск, бульвар Архитекторов (2026 год)")


def test_строка_в_скобках_не_становится_названием():
    data = _docx(["(2026 год)", "Информация по докладу Минстроя России"])
    assert doc_text.title_from("и.docx", data) == "Информация по докладу Минстроя России"


def test_обычный_заголовок_берётся_как_есть():
    data = _docx(["Информация по докладу Минстроя России.", "Текст справки"])
    assert doc_text.title_from("и.docx", data) == "Информация по докладу Минстроя России"


def test_перенос_строки_внутри_абзаца_не_склеивает_слова():
    """«…и НТР» + перенос + «Ямало-Ненецкого» давали «НТРЯмало-Ненецкого»."""
    from docx.oxml.ns import qn
    doc = Document()
    p = doc.add_paragraph()
    run = p.add_run("Бриф о системе профессионального образования и НТР")
    run._r.append(run._r.makeelement(qn("w:br"), {}))
    p.add_run("Ямало-Ненецкого автономного округа")
    buffer = io.BytesIO()
    doc.save(buffer)
    # заодно длинное наименование округа сворачивается в привычное «ЯНАО»
    assert doc_text.title_from("бриф.docx", buffer.getvalue()) == (
        "Бриф о системе профессионального образования и НТР ЯНАО")


def test_обрывок_с_маленькой_буквы_не_становится_названием():
    data = _docx(["по организационному обеспечению департамента образования",
                  "Справка о развитии округа"])
    assert doc_text.title_from("с.docx", data) == "Справка о развитии округа"


def test_бланк_организации_не_становится_названием():
    """«ПРАВИТЕЛЬСТВО РОССИЙСКОЙ ФЕДЕРАЦИИ» — это бумага, а не название документа."""
    data = _docx(["ПРАВИТЕЛЬСТВО РОССИЙСКОЙ ФЕДЕРАЦИИ",
                  "ПОСТАНОВЛЕНИЕ",
                  "О проведении эксперимента по оценке качества образования"])
    assert doc_text.title_from("док.docx", data) == \
        "О проведении эксперимента по оценке качества образования"


def test_имя_файла_спасает_нечитаемый_документ():
    """В презентации или скане заголовка нет — зато человек назвал файл осмысленно."""
    assert doc_text.propose("10. Одностраничник по Положению о комиссии.pdf", b"") == \
        "Одностраничник по Положению о комиссии"
    assert doc_text.propose("09. Макет экрана %22Стоимость обучения%22.pdf", b"") == \
        "Макет экрана «Стоимость обучения»"
    # а техническое имя без документа даёт только себя — придумывать нечего
    assert doc_text.propose("АН-1466 от 15.04.2026.pdf", b"") == "АН-1466 от 15.04.2026"
