"""Короткое название: сокращаем то, что человек и так говорит коротко."""
from app import wording


def test_ведомство_сокращается_с_сохранением_падежа():
    assert wording.shorten("Позиция Министерства строительства и жилищно-коммунального "
                           "хозяйства Российской Федерации") == "Позиция Минстроя России"
    assert wording.shorten("Письмо в Министерство строительства и жилищно-коммунального "
                           "хозяйства") == "Письмо в Минстрой России"
    assert wording.shorten("Доклад Министерства финансов Российской Федерации") == \
        "Доклад Минфина России"


def test_округ_сворачивается_в_привычное_сокращение():
    assert wording.shorten("Справка о развитии Ямало-Ненецкого автономного округа "
                           "в сфере образования") == "Справка о развитии ЯНАО в сфере образования"


def test_общеобразовательная_организация_это_школа():
    assert wording.shorten("О капитальном ремонте общеобразовательных организаций") == \
        "О капитальном ремонте школ"
    # падеж читается по предлогу: «в организации» — «в школе», иначе — «школы»
    assert wording.shorten("Об организации питания в общеобразовательной организации") == \
        "Об организации питания в школе"
    assert wording.shorten("О строительстве общеобразовательной организации на 550 мест") == \
        "О строительстве школы на 550 мест"
    assert wording.shorten("Направление в общеобразовательную организацию педагогов") == \
        "Направление в школу педагогов"


def test_канцелярия_снимается():
    assert wording.shorten("Информация по вопросу об организационном обеспечении") == \
        "Информация об организационном обеспечении"
    assert wording.shorten("Информационная справка о работе, подготовленная к совещанию") == \
        "Справка о работе"


def test_название_человека_не_трогаем():
    assert wording.shorten("Позиция Минстроя России") == "Позиция Минстроя России"
    assert wording.shorten("Сводка по школам") == "Сводка по школам"


def test_жанр_документа_встаёт_первым_словом():
    # повестка и список участников называются собой — что внутри, и так ясно
    assert wording.entitle("Создание эталонной системы показателей", "Повестка.docx") == "Повестка"
    assert wording.entitle("Заседание рабочей группы", "02. Список участников.docx") == \
        "Список участников"
    # остальные жанры приписываются к сути
    assert wording.entitle("О системе общего образования Свердловской области",
                           "Бриф_Свердловская область.docx") == \
        "Бриф о системе общего образования Свердловской области"
    assert wording.entitle("Создание эталонной системы", "Бриф_4.docx") == \
        "Бриф – Создание эталонной системы"


def test_заголовок_главнее_имени_файла():
    # файл назвали справкой, а внутри информация — информацией и остаётся
    assert wording.entitle("Информация по докладу Минстроя России", "Инф_справка_ТН.docx") == \
        "Информация по докладу Минстроя России"
    assert wording.entitle("Справка о развитии округа", "письмо.docx") == \
        "Справка о развитии округа"


def test_без_жанра_название_не_трогаем():
    assert wording.entitle("О развитии профессионального образования", "письмо.docx") == \
        "О развитии профессионального образования"


def test_человеческое_имя_файла_главнее_заголовка():
    """Пользователь сам назвал файл — он объяснил документ лучше его первой строки."""
    from app import naming
    assert naming.looks_human("Проект постановления Правительства РФ о проведении эксперимента")
    assert naming.looks_human("Одностраничник по Положению о межведомственной комиссии")
    # а это пометка для себя, а не название
    assert not naming.looks_human("Инф_справка_ТН_2026 РФ")
    assert not naming.looks_human("АН-1466 от 15.04.2026")
    assert not naming.looks_human("Повестка")


def test_имя_из_интернета_расшифровывается():
    from app import naming
    assert naming.from_filename("09. Макет экрана %22Стоимость обучения в вузах%22.pdf") == \
        "Макет экрана «Стоимость обучения в вузах»"
