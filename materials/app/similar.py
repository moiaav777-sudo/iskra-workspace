"""Похоже или не похоже: подсказки, а не решения.

Документ прилетает один, без объяснений, и сервис должен подсказать две вещи:
к какому мероприятию он скорее всего относится и не лежит ли там уже его прежняя
версия. Обе подсказки человек видит рядом с кнопками и решает сам — поэтому здесь
нарочно нет ничего умного: слова, даты и точное совпадение байтов.
"""
from __future__ import annotations

import hashlib
import re

DATE = re.compile(r"\b(\d{2})\.(\d{2})\.(\d{4})\b")
WORD = re.compile(r"[а-яёa-z0-9-]{4,}", re.I)

# Слова, которые есть в каждой второй справке: на них «похожесть» не строится.
COMMON = {
    "информация", "справка", "доклад", "материалы", "материал", "вопрос", "вопросу",
    "совещание", "совещания", "совещанию", "россии", "российской", "федерации",
    "образования", "образование", "министерства", "министерство", "предложения",
    "позиция", "сведения", "данные", "отчёт", "отчет", "проект", "общие",
}


def digest(data: bytes) -> str:
    """Отпечаток файла: совпал — это тот же самый файл, байт в байт."""
    return hashlib.sha1(data).hexdigest()


def words(text: str) -> set[str]:
    """Значимые слова строки, приведённые к одному виду."""
    return {w.lower() for w in WORD.findall(text or "")} - COMMON


def overlap(left: set[str], right: set[str]) -> float:
    """Доля общего от меньшего набора: 1.0 — одно целиком внутри другого."""
    if not left or not right:
        return 0.0
    return len(left & right) / min(len(left), len(right))


def dates(text: str) -> set[str]:
    """Даты вида ДД.ММ.ГГГГ, встреченные в тексте документа."""
    return {f"{d}.{m}.{y}" for d, m, y in DATE.findall(text or "")}
