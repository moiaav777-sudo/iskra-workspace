"""Из заголовка документа — короткое название, по которому понятно, что это.

В папке человек читает не титульный лист, а строку реестра. «Информация по вопросу
об организационном обеспечении департамента образования Ямало-Ненецкого автономного
округа» не говорит ему ничего сверх того, что скажет «Информация об организационном
обеспечении департамента образования ЯНАО», — зато занимает полторы строки.

Поэтому длина здесь не цель: название сокращается там, где слова ничего не несут, —
официальные наименования сворачиваются до привычных («Минстроя России», «ЯНАО»),
а канцелярские обороты снимаются. Получится двадцать знаков — пусть будет двадцать,
получится полтораста — значит, столько и нужно для понимания.

Это предложение, а не приговор: название человек правит в рамке входящих, и то,
что он вписал руками, сервис уже не трогает.
"""
from __future__ import annotations

import re

from . import naming

# Жанр документа — слово, с которого человек начинает название вслух: «Бриф о системе
# профессионального образования», «Справка о развитии округа», «Список участников».
# Заголовок внутри документа жанра обычно не называет: повестка начинается с первого
# вопроса, бриф — с шапки письма. Поэтому жанр ищем ещё и в имени файла.
#
# «Повестка» и «Список участников» — названия целиком: что в них, и так понятно.
# Остальные жанры приписываются к сути: «Бриф» + «О системе…» = «Бриф о системе…».
WHOLE = {"Повестка", "Список участников"}
MORE = [("Проект постановления", ("проект постановления",)),
        ("Одностраничник", ("одностраничник",)),
        ("Макет экрана", ("макет экрана",)),
        ("Справка", ("справка",)),
        ("Информация", ("информация",)),
        ("Предложения", ("предложения",)),
        ("Позиция", ("позиция",)),
        ("Доклад", ("доклад",))]


def _genres() -> list[tuple[str, tuple[str, ...]]]:
    return [(title, hints) for _, title, hints in naming.ROLES] + MORE


def genre_of(text: str) -> str | None:
    """Жанр документа по тексту-подсказке: названию, имени файла, первым строкам.

    Слово должно стоять в начале строки, а не встречаться где попало. Иначе
    «Информация об участниках долевого строительства» становится «Списком
    участников», а настоящее название исчезает: имя файла — единственное место,
    где оно живёт.
    """
    return naming.opens_with(text, _genres())


def entitle(title: str, hints: str = "") -> str:
    """Название с жанром впереди. Жанра не видно — оставляем как есть.

    Заголовок главнее имени файла: «Информация по докладу Минстроя России»
    из файла «Инф_справка_ТН.docx» остаётся информацией, а не становится справкой.
    """
    title = (title or "").strip(" .;:")
    own = genre_of(title)
    if own:
        return own if own in WHOLE else title
    genre = genre_of(hints)
    if not genre:
        return title
    if genre in WHOLE or not title:
        return genre
    if re.match(r"^об?\s", title, re.I):          # «О системе…» → «Бриф о системе…»
        return f"{genre} {title[0].lower()}{title[1:]}"
    return f"{genre} – {title}"


def _cases(stem: str, endings: dict[str, str]):
    """Замена с сохранением падежа: «доклад Министерства…» → «доклад Минстроя России»."""
    def repl(m: re.Match) -> str:
        return stem + endings.get((m.group(1) or "").lower(), endings[""])
    return repl


# Падежи ведомств: «Минстрой России направил», «позиция Минстроя России».
# Два набора окончаний: у «Минстрой» основа кончается на гласную, у «Минфин» — на согласную.
_MIN = {"о": "й России", "": "й России", "а": "я России",
        "у": "ю России", "ом": "ем России", "е": "е России"}
_MIN_HARD = {"о": " России", "": " России", "а": "а России",
             "у": "у России", "ом": "ом России", "е": "е России"}
_SLUZHBA = {"а": "", "": "а", "ы": "а", "е": "у", "у": "", "ой": "ом"}

# «Общеобразовательная организация» — это школа, и человек говорит «школа».
# Падеж у «организации» один на четыре случая, поэтому смотрим на предлог перед ней:
# «в организации» — «в школе», «доклад организации» — «доклад школы».
_SCHOOL = {"я": "школа", "ю": "школу", "ей": "школой", "й": "школ",
           "ях": "школах", "ям": "школам", "ями": "школами"}
_SCHOOL_PREP = {"в", "во", "на", "о", "об", "обо", "при", "к", "ко"}


def _school(m: re.Match) -> str:
    prep = (m.group(1) or "").strip()
    ending = m.group(2).lower()
    if ending == "и":
        word = "школе" if prep.lower() in _SCHOOL_PREP else "школы"
    else:
        word = _SCHOOL[ending]
    return f"{prep} {word}" if prep else word

# Порядок важен: сначала длинные обороты, потом короткие.
RULES: list[tuple[re.Pattern, object]] = [
    # ── канцелярские обороты: слова есть, смысла нет ──────────────────────
    (re.compile(r"^Информационн(?:ая|о-аналитическая)\s+справка", re.I), "Справка"),
    (re.compile(r"\s+по\s+вопрос(?:у|ам)\s+", re.I), " "),
    (re.compile(r",?\s+подготовленн\w+[^,.]*", re.I), ""),
    (re.compile(r",?\s+в\s+соответствии\s+с[^,.]*", re.I), ""),
    (re.compile(r",?\s+во\s+исполнение[^,.]*", re.I), ""),
    (re.compile(r"\s+на\s+\d+\s+листах?", re.I), ""),

    # ── ведомства ─────────────────────────────────────────────────────────
    (re.compile(r"Министерств(о|а|у|ом|е)\s+строительства\s+и\s+жилищно-коммунального"
                r"\s+хозяйства(?:\s+Российской\s+Федерации)?", re.I),
     _cases("Минстро", _MIN)),
    (re.compile(r"Министерств(о|а|у|ом|е)\s+просвещения(?:\s+Российской\s+Федерации)?", re.I),
     "Минпросвещения России"),
    (re.compile(r"Министерств(о|а|у|ом|е)\s+науки\s+и\s+высшего\s+образования"
                r"(?:\s+Российской\s+Федерации)?", re.I), "Минобрнауки России"),
    (re.compile(r"Федеральн\w+\s+служб(а|ы|е|у|ой)\s+по\s+надзору\s+в\s+сфере"
                r"\s+образования\s+и\s+науки", re.I), _cases("Рособрнадзор", _SLUZHBA)),
    (re.compile(r"Федеральн\w+\s+служб\w*\s+по\s+надзору\s+в\s+сфере\s+защиты\s+прав"
                r"\s+потребителей\s+и\s+благополучия\s+человека", re.I), "Роспотребнадзора"),

    # ── регионы: привычные сокращения, они и в речи звучат так ────────────
    (re.compile(r"Ямало-Ненецк\w+\s+автономн\w+\s+округ\w*", re.I), "ЯНАО"),
    (re.compile(r"Ненецк\w+\s+автономн\w+\s+округ\w*", re.I), "НАО"),
    (re.compile(r"Ханты-Мансийск\w+\s+автономн\w+\s+округ\w*(?:\s*[—–-]\s*Югр\w+)?", re.I),
     "ХМАО — Югры"),
    (re.compile(r"Чукотск\w+\s+автономн\w+\s+округ\w*", re.I), "ЧАО"),
    (re.compile(r"Еврейск\w+\s+автономн\w+\s+област\w*", re.I), "ЕАО"),

    # ── ведомства с основой на согласную ──────────────────────────────────
    (re.compile(r"Министерств(о|а|у|ом|е)\s+финансов(?:\s+Российской\s+Федерации)?", re.I),
     _cases("Минфин", _MIN_HARD)),
    (re.compile(r"Министерств(о|а|у|ом|е)\s+труда\s+и\s+социальной\s+защиты"
                r"(?:\s+Российской\s+Федерации)?", re.I), _cases("Минтруд", _MIN_HARD)),
    (re.compile(r"Министерств(о|а|у|ом|е)\s+здравоохранения(?:\s+Российской\s+Федерации)?", re.I),
     _cases("Минздрав", _MIN_HARD)),
    (re.compile(r"Министерств(о|а|у|ом|е)\s+спорта(?:\s+Российской\s+Федерации)?", re.I),
     _cases("Минспорт", _MIN_HARD)),
    (re.compile(r"Министерств(?:о|а|у|ом|е)\s+экономического\s+развития"
                r"(?:\s+Российской\s+Федерации)?", re.I), "Минэкономразвития России"),
    (re.compile(r"Министерств(?:о|а|у|ом|е)\s+культуры(?:\s+Российской\s+Федерации)?", re.I),
     "Минкультуры России"),
    (re.compile(r"Министерств(?:о|а|у|ом|е)\s+цифрового\s+развития[^,.]*?коммуникаций", re.I),
     "Минцифры России"),
    (re.compile(r"Федеральн\w+\s+агентств\w+\s+по\s+делам\s+молодёжи", re.I), "Росмолодёжи"),
    (re.compile(r"Государственн\w+\s+Дум\w+(?:\s+Федерального\s+Собрания)?"
                r"(?:\s+Российской\s+Федерации)?", re.I), "Госдумы"),

    # ── школы: человек называет их школами ────────────────────────────────
    (re.compile(r"(?:(в|во|на|о|об|обо|при|к|ко)\s+)?общеобразовательн\w+\s+"
                r"организаци(я|и|ю|ей|й|ях|ям|ями)\b", re.I), _school),

    # ── прочее ────────────────────────────────────────────────────────────
    (re.compile(r"научно-техн(?:ическ|ологическ)\w+\s+развития", re.I), "НТР"),
    (re.compile(r"\s+Российской\s+Федерации", re.I), " России"),
    (re.compile(r"\s+субъект(ах|ов|ам)\s+России\b", re.I), r" субъект\1 России"),
]


def shorten(title: str) -> str:
    """Короткое название документа из его заголовка."""
    text = (title or "").strip()
    if not text:
        return ""
    for pattern, repl in RULES:
        text = pattern.sub(repl, text)
    text = re.sub(r"\s+", " ", text).strip(" ,.;:—–-")
    if text and text[0].islower():
        text = text[0].upper() + text[1:]
    return text
