UNKNOWN_RANK = 9999

_DEPUTY_PREFIXES = ("заместитель", "врио")
_REGIONAL_MARKERS = ("республики", "области", "края", "округа", "города",
                     "республика", "область", "край", "округ", "город",
                     "москв", "петербург", "севастопол")


def protocol_rank(role: str) -> int:
    """Ранг должности по протокольному старшинству; 9999 — не определено.

    Ранг получают ТОЛЬКО должности из указа 746:
    - «заместитель X» / «врио X» ранжируется лишь если «заместитель X»
      явно есть в указе (напр. «заместитель министра» = 30), иначе это
      заместитель главы — вне списка;
    - региональный председатель/заместитель председателя правительства
      субъекта (Чеченской Республики, области и т.п.) — вне федерального списка.
    """
    r = (role or "").strip().lower()
    if not r:
        return UNKNOWN_RANK
    best_rank = UNKNOWN_RANK
    best_len = 0
    best_kw = ""
    for rank, kw in PROTOCOL_KEYWORDS:
        if kw in r and len(kw) > best_len:
            best_rank = rank
            best_len = len(kw)
            best_kw = kw
    if not best_kw:
        return UNKNOWN_RANK
    # «заместитель X» / «врио X» — ранжируется только если должность-заместитель явно в указе 746
    first_word = r.split()[0]
    if first_word in _DEPUTY_PREFIXES and not best_kw.startswith(("заместитель", "первый заместитель")):
        return UNKNOWN_RANK
    # региональный председатель/заместитель председателя правительства — вне федерального списка
    _FEDERAL_ONLY = ("председатель правительства", "заместитель председателя правительства",
                     "первый заместитель председателя правительства", "министр",
                     "заместитель министра", "первый заместитель министра",
                     "статс-секретарь")
    if best_kw in _FEDERAL_ONLY:
        if "российской федерации" not in r and "федеральн" not in r and " рф" not in r and any(m in r for m in _REGIONAL_MARKERS):
            return UNKNOWN_RANK
    return best_rank


def sort_key(rank: int, name: str = "") -> tuple:
    """Ключ сортировки: ранг по возрастанию (меньше — выше), внутри ранга — по алфавиту фамилии, 9999 — в конец."""
    surname = ""
    if name and name.strip():
        surname = name.strip().split()[0].lower()
    return (0 if rank != UNKNOWN_RANK else 1, rank, surname)
