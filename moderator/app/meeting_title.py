"""Короткое название совещания — одно правило на всё пространство.

Официальное название длинное и почти всегда одинаковое в начале: «Совещание у Заместителя
Председателя Правительства Российской Федерации Д.Н. Чернышенко по вопросам обеспечения
жильём детей-сирот». Совещания у пользователя проходят у одного и того же человека
(решение от 21.09), поэтому кто проводит — шум: в списке их отличает только тема.
Короткое название — это тема: «Обеспечение жильём детей-сирот».

Раньше короткое имя придумывал каждый сам: портал писал «Чернышенко Д.Н. по вопросам…»,
«Бриф» — «у Зампреда Правительства РФ…». Теперь правило одно. Считает его «Модератор» и
отдаёт полем `short_title`, человек может поправить его в карточке совещания; остальные
только показывают. Правится этот файл, копии раскладывает `portal/scripts/sync_shared.sh`.
"""
from __future__ import annotations

import re

_TOPIC = re.compile(r"\s+по\s+вопрос(?:у|ам)\s+(.+)$", re.I)

# Первое слово темы стоит в родительном падеже: «по вопросам обеспечения …». Ставим его
# в именительный, но только когда уверены: отглагольные и подобные существительные с
# известным окончанием. Не узнали слово — тему не переписываем, а оставляем «По вопросам …»:
# лучше длиннее, чем «Итогового сочинения» с висящим падежом.
_NOMINATIVE = [
    ("ения", "ение"), ("ания", "ание"), ("ития", "итие"), ("тия", "тие"),
    ("ции", "ция"), ("ии", "ия"), ("ства", "ство"), ("ки", "ка"),
]


def _nominative(word: str) -> str | None:
    low = word.lower()
    for tail, repl in _NOMINATIVE:
        if low.endswith(tail) and len(low) > len(tail) + 2:
            return word[: len(word) - len(tail)] + repl
    return None


def short_title(title: str) -> str:
    """Тема совещания без того, кто его проводит.

    >>> short_title("Совещание у Заместителя Председателя Правительства Российской Федерации "
    ...             "Д.Н. Чернышенко по вопросам обеспечения жильем детей-сирот")
    'Обеспечение жильем детей-сирот'
    """
    full = re.sub(r"\s+", " ", title or "").strip()
    full = re.sub(r"\s+Российской Федерации\b", " РФ", full)
    m = _TOPIC.search(full)
    if not m:
        return full
    topic = m.group(1).strip()
    first, _, rest = topic.partition(" ")
    nom = _nominative(first)
    if nom:
        text = nom + (" " + rest if rest else "")
    else:
        which = "вопросу" if re.search(r"по\s+вопросу\s", full, re.I) else "вопросам"
        text = f"по {which} {topic}"
    return text[:1].upper() + text[1:]
