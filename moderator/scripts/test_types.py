"""Проверка определения ТИПА документа через Искру."""
import json, sys, time
sys.path.insert(0, ".")
from app import llm_extract

moderator_doc = """Вступительное слово
Чернышенко Дмитрий Николаевич – Заместитель Председателя Правительства Российской Федерации

Коллеги, добрый день! Сегодня проводим совещание по вопросу обеспечения жилищных прав детей-сирот и детей, оставшихся без попечения родителей.
Это одна из наиболее чувствительных социальных задач и безусловное обязательство государства.

Вопрос 1
Уважаемый Никита Евгеньевич, прошу доложить о текущей ситуации по обеспечению жилищных прав.
Спасибо, Никита Евгеньевич. Отметим, что темпы растут, но остаются риски.

Подведение итогов
Коллеги, по итогам обсуждения прошу зафиксировать поручения и обеспечить контроль.
"""

participants_doc = """СПИСОК участников совещания
БУГАЕВ Александр Вячеславович – Первый заместитель Министра просвещения Российской Федерации (очно)
КАДОЧНИКОВ Павел Анатольевич – Заместитель Министра финансов Российской Федерации (ВКС)
СТАСИШИН Никита Евгеньевич – Заместитель Министра строительства и жилищно-коммунального хозяйства Российской Федерации (очно)
БАРИНОВА Ольга Александровна – помощник Заместителя Председателя Правительства Российской Федерации (очно)
"""

orders_doc = """ПРОЕКТ ПЕРЕЧНЯ ПОРУЧЕНИЙ
1. Минстрою России (И.Э. Файзуллину) обеспечить завершение мероприятий по предоставлению жилья детям-сиротам в установленные сроки. Срок – до 1 октября 2026 г.
2. Минпросвещения России (С.С. Кравцову) совместно с регионами актуализировать региональные программы. Срок – до 15 октября 2026 г.
"""

for name, doc in [("модератор", moderator_doc), ("участники", participants_doc), ("поручения", orders_doc)]:
    t0 = time.time()
    try:
        r = llm_extract.extract(doc)
        dt = time.time() - t0
        print(f"\n=== {name} ({dt:.0f} с) ===")
        print("  doc_type:", r.get("doc_type"), "| confidence:", r.get("confidence"))
        print("  summary:", r.get("summary"))
        print("  data keys:", list((r.get("data") or {}).keys()))
    except Exception as e:
        print(f"\n=== {name} ОШИБКА: {type(e).__name__} {e}")
